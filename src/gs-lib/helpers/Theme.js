const applyPadding = (pad, side) => {
  const padding = {
    top: {
      paddingTop: pad,
      boxSizing: "border-box"
    },
    right: {
      paddingRight: pad,
      boxSizing: "border-box"
    },
    bottom: {
      paddingBottom: pad,
      boxSizing: "border-box"
    },
    left: {
      paddingLeft: pad,
      boxSizing: "border-box"
    },
    vertical: {
      paddingTop: pad,
      paddingBottom: pad,
      boxSizing: "border-box"
    },
    horizontal: {
      paddingLeft: pad,
      paddingRight: pad,
      boxSizing: "border-box"
    },
    all: {
      paddingLeft: pad,
      paddingRight: pad,
      paddingTop: pad,
      paddingBottom: pad,
      boxSizing: "border-box"
    }
  };

  if (side) {
    return padding?.[side];
  }
  return padding;
};

